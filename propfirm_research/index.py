"""Rebuild research/INDEX.md from the front-matter of every item (studies, hypotheses, decisions, reviews).

Usage: python -m propfirm_research.index
"""

import re
import sys
from pathlib import Path

from . import paths

FOLDERS = ["decisions", "hypotheses", "reviews", "studies", "strategies"]
FM = re.compile(r"^---\n(.*?)\n---\n", re.S)


def front_matter(text: str) -> dict:
    m = FM.match(text)
    if not m:
        return {}
    out = {}
    for line in m.group(1).splitlines():
        if ":" in line:
            k, v = line.split(":", 1)
            out[k.strip()] = v.split("#", 1)[0].strip()
    return out


def build(root: Path) -> str:
    rows = []
    for folder in FOLDERS:
        for f in sorted((root / folder).rglob("*.md")):
            if f.name.startswith("_"):
                continue
            fm = front_matter(f.read_text())
            if not fm.get("id"):
                continue
            rel = f.relative_to(root).as_posix()
            rows.append((fm["id"], fm.get("title", ""), fm.get("status", ""), fm.get("updated", ""), rel))
    rows.sort()
    lines = ["# Index", "", "Generated by `python -m propfirm_research.index`. Do not edit by hand.", "",
             "| Id | Title | Status | Updated | File |", "|---|---|---|---|---|"]
    lines += [f"| {i} | {t} | {s} | {u} | [{r}]({r}) |" for i, t, s, u, r in rows]
    return "\n".join(lines) + "\n"


def main() -> int:
    (paths.RESEARCH_DIR / "INDEX.md").write_text(build(paths.RESEARCH_DIR))
    print(f"wrote {paths.RESEARCH_DIR / 'INDEX.md'}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
